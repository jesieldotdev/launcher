package dev.jesiel.launcher.data

/**
 * Guia em texto do formato dos widgets HTML, para colar em outra IA (ChatGPT, Claude, Gemini…)
 * e pedir um widget pronto. Montado a partir de [HtmlVariables.all], então acompanha o app.
 */
object HtmlWidgetGuide {

    fun build(currentHtml: String? = null, interactive: Boolean = false, network: Boolean = false): String = buildString {
        appendLine("# Widget HTML para o Launcher (Android)")
        appendLine()
        appendLine("Você vai criar um widget para a tela inicial de um launcher Android. O widget é um trecho de HTML/CSS (e JS opcional) desenhado num WebView do tamanho exato do widget, por cima do papel de parede.")
        appendLine()
        appendLine("## Formato da resposta")
        appendLine("- Responda com UM bloco de código contendo só: `<style>…</style>`, o HTML do widget e, se precisar, `<script>…</script>`.")
        appendLine("- Não escreva `<!doctype>`, `<html>`, `<head>` nem `<body>`: o launcher monta a página.")
        appendLine("- Depois do código, diga em uma linha quais opções ligar no editor: **Interativo** (se usar JavaScript) e/ou **Acesso à internet** (se usar fontes, imagens ou dados online).")
        appendLine()
        appendLine("## A página que o launcher monta")
        appendLine("- `html, body { margin:0; padding:0; height:100%; overflow:hidden; background:transparent }`.")
        appendLine("- Seleção de texto e menu de toque longo ficam desligados (o toque longo é do launcher: abre o menu do widget).")
        appendLine("- O WebView tem o tamanho do widget, então `100vw`/`100vh` = largura/altura do widget. Faça o elemento raiz ocupar `width:100%; height:100%` e use unidades relativas (`vw`, `vh`, `%`, `min(…)`, ou `container-type:size` com `cqw`/`cqh`) para caber em qualquer tamanho. Tamanhos comuns: de 2×1 a 4×2 células (largo e baixo).")
        appendLine("- O fundo é transparente: o papel de parede aparece atrás. Para um cartão, use cores com transparência (ex.: `rgba(0,0,0,.45)`). `backdrop-filter` não desfoca o papel de parede (a página não o enxerga).")
        appendLine("- Sem rolagem por padrão. Uma área rolável interna (`overflow-y:auto`) funciona, mas o resto do widget deve caber.")
        appendLine("- `localStorage` e cookies não estão disponíveis; não há acesso a arquivos.")
        appendLine()
        appendLine("## Variáveis")
        appendLine("Use de três formas:")
        appendLine("1. **Texto/atributo:** `{{nome}}`, ex.: `<b>{{hora}}</b>`, `<img src=\"{{musicaCapa}}\">`.")
        appendLine("2. **CSS:** `var(--nome)`. Números vêm sem aspas (dá para usar em `calc(var(--bateria) * 1%)`), cores `#rrggbb` sem aspas, textos entre aspas (servem em `content:`).")
        appendLine("3. **JavaScript (só no modo Interativo):** objeto `launcher` (ex.: `launcher.hora`) e a função `function onLauncherData(d) { … }`, chamada ao carregar e sempre que um valor muda, sem recarregar a página.")
        appendLine()
        appendLine("Todas as variáveis são texto. Cada uma tem um nome em português e um em inglês, com o mesmo valor (ex.: `{{hora}}` = `{{time}}`, `var(--bateria)` = `var(--battery)`). Use um dos dois. Lista (português / inglês):")
        HtmlVariables.all.forEach { (k, d) -> appendLine("- `$k` / `${HtmlVariables.english[k] ?: k}`: $d") }
        appendLine()
        appendLine("Observações:")
        appendLine("- Só as variáveis citadas no código são calculadas (o launcher procura `{{nome}}`, `var(--nome)` e `launcher.nome`). Se ler um valor como `d.nome` dentro de `onLauncherData`, cite também `launcher.nome` em algum lugar (um comentário basta) para ele ser calculado.")
        appendLine("- A hora muda a cada minuto; `musicaPosicao`/`musicaProgresso` a cada segundo enquanto a música toca.")
        appendLine("- Variáveis `musica*` e `notificacoes` precisam de \"acesso a notificações\" (versão completa do app); sem ele vêm vazias, então trate o caso vazio (ex.: \"Nada tocando\").")
        appendLine("- Cores do Material You (`corPrimaria`, `corFundo`…) seguem o papel de parede e o modo claro/escuro. Para transparência use `color-mix(in srgb, var(--corPrimaria) 35%, transparent)`.")
        appendLine("- Fora do modo Interativo, `{{…}}` é trocado e a página redesenha quando um valor muda. No modo Interativo, `{{…}}` em texto atualiza sozinho; em atributos não — para trocar uma imagem use `<img data-lsrc=\"musicaCapa\" src=\"{{musicaCapa}}\">` ou atualize em `onLauncherData`.")
        appendLine()
        appendLine("## Links e ações")
        appendLine("Use `<a href=\"…\">` (funciona com ou sem JavaScript):")
        appendLine("- `launcher://app/<pacote>` abre um app (ex.: `launcher://app/com.whatsapp`).")
        appendLine("- `launcher://apps` lista de apps · `launcher://busca` busca · `launcher://painel` painel de controle · `launcher://notificacoes` notificações · `launcher://ajustes` ajustes do launcher.")
        appendLine("- `launcher://musica/alternar`, `/tocar`, `/pausar`, `/proxima`, `/anterior`; `launcher://musica` abre o app que está tocando.")
        appendLine("- Em inglês também valem: `launcher://music/toggle`, `/play`, `/pause`, `/next`, `/previous`, `launcher://search`, `launcher://panel`, `launcher://notifications`, `launcher://settings`.")
        appendLine("- `launcher://desbloquear` (ou `unlock`): na tela de bloqueio do Launcher, pede o desbloqueio.")
        appendLine("- `launcher://fechar` (ou `close`) fecha a lista de apps em HTML; `launcher://info/<pacote>` abre as informações do app; `launcher://desinstalar/<pacote>` (ou `uninstall`) pede para desinstalar.")
        appendLine("- `https://…` abre no navegador interno.")
        appendLine()
        appendLine("## Lista de apps e telas cheias")
        appendLine("O mesmo formato serve para três usos: widget na área de trabalho, **tela de bloqueio** e **lista de apps** (abre no lugar da gaveta do tema). Nos dois últimos a página ocupa a tela inteira.")
        appendLine("- `launcher.appsLista` (ou `appsList`) é um JSON em texto: `JSON.parse(d.appsLista)` dá `[{nome, pacote, categoria, letra, favorito, dock, icone}]` (também com os nomes `name, package, category, letter, favorite, icon`), em ordem alfabética. `appsRecentes` (`recentApps`) tem o mesmo formato, com os últimos abertos. `appsTotal` é a quantidade.")
        appendLine("- Ícone de cada app: `<img src=\"launcher-icon://<pacote>\">` (é o campo `icone`). Use `loading=\"lazy\"` em listas longas.")
        appendLine("- Abrir um app: `<a href=\"launcher://app/<pacote>\">` ou `location.href = 'launcher://app/' + pacote` (a lista fecha sozinha).")
        appendLine("- `modoBusca` (`searchMode`) é \"sim\" quando a lista foi aberta pelo botão de busca: foque o campo de busca nesse caso.")
        appendLine("- `barraTopo` / `barraBase` (`insetTop` / `insetBottom`): altura das barras do sistema, em px do CSS. Ex.: `padding-top: calc(var(--barraTopo) * 1px + 12px)`.")
        appendLine("- Em tela cheia use `position:fixed; inset:0` no elemento raiz e uma área rolável interna (`overflow-y:auto`). O botão Voltar do Android fecha a lista.")
        appendLine("- A lista de apps precisa do modo **Interativo**.")
        appendLine()
        appendLine("## Bateria e desempenho")
        appendLine("- O widget é pausado quando a tela inicial não está visível (timers e animações param).")
        appendLine("- Prefira o modo sem JavaScript quando der. Com JS, evite `setInterval` abaixo de 1 s e animações contínuas pesadas; use CSS simples.")
        appendLine("- Com internet: `fetch` precisa de CORS liberado pelo servidor; consulte no máximo a cada ~30 s. Fontes do Google Fonts funcionam (`@import` ou `<link>`).")
        appendLine()
        appendLine("## Exemplo mínimo")
        appendLine("```html")
        appendLine("<style>")
        appendLine(".w{height:100%;box-sizing:border-box;padding:6% 7%;border-radius:22px;color:#fff;font-family:sans-serif;")
        appendLine("  background:rgba(0,0,0,.4);display:flex;flex-direction:column;justify-content:center}")
        appendLine(".h{font-size:min(38vh,22vw);font-weight:200;line-height:1}")
        appendLine(".b{height:4px;border-radius:2px;background:rgba(255,255,255,.25);margin-top:6%}")
        appendLine(".b i{display:block;height:100%;border-radius:2px;width:calc(var(--bateria) * 1%);background:var(--corPrimaria)}")
        appendLine("</style>")
        appendLine("<div class=\"w\"><div class=\"h\">{{hora}}</div><div>{{saudacao}} · {{data}}</div><div class=\"b\"><i></i></div></div>")
        appendLine("```")
        if (!currentHtml.isNullOrBlank()) {
            appendLine()
            appendLine("## Código atual do widget")
            appendLine("Opções ligadas agora: Interativo = ${if (interactive) "sim" else "não"}, Acesso à internet = ${if (network) "sim" else "não"}.")
            appendLine("```html")
            appendLine(currentHtml.trimEnd())
            appendLine("```")
        }
        appendLine()
        appendLine("## Pedido")
        append(if (currentHtml.isNullOrBlank()) "Crie um widget: [descreva aqui o que você quer]" else "Altere o widget acima: [descreva aqui o que mudar]")
    }
}
